from pathlib import Path
import json,hashlib,re,collections,datetime
from pipeline_paths import ROOT
from pipeline_paths import GAME
SOURCES={'install':GAME/'xtlr_Data/StreamingAssets/InstallResource/txtp','version':GAME/'Persistent_Store/SoundBanks/txtp'}
def sha(p): return hashlib.file_digest(p.open('rb'),'sha256').hexdigest()
def dump(p,v):
 p=ROOT/p;p.parent.mkdir(parents=True,exist_ok=True);p.write_text(json.dumps(v,ensure_ascii=False,indent=2),encoding='utf8')
def scan():
 rows=[]
 for origin,base in SOURCES.items():
  for p in sorted(base.glob('*.txtp')):
   row={'source':origin,'path':str(p),'filename':p.name,'size':p.stat().st_size,'mtime_ns':p.stat().st_mtime_ns}
   if re.search('[\u3400-\u9fff]',p.name):
    row['status']='deferred_user_editing';rows.append(row);continue
   row['sha256']=sha(p)
   if 'transition' in p.name.lower():
    row['status']='excluded_transition';rows.append(row);continue
   text=p.read_text(encoding='utf-8-sig');bank=re.search(r'Music_[A-Za-z]+',p.name)
   row.update(status='inventoried',bank=bank.group() if bank else 'unknown',gamesyncs=[{'group_id':int(a),'value_id':int(b)} for a,b in re.findall(r'\((\d+)=(\d+)\)',p.name)],recipe=text.split('# AUTOGENERATED')[0].strip(),wem_ids=sorted(set(re.findall(r'(\d+)\.wem',text))),event_ids=re.findall(r'CAkEvent\[\d+\]\s+(\d+)',text),duration_ms=[float(x) for x in re.findall(r'fDuration: ([\d.]+)',text)],random='{r}' in p.name)
   row['id']=origin+'-'+hashlib.sha256(p.name.encode()).hexdigest()[:12]
   row['category']={'Music_Outfit':'outfit','Music_AVG':'story','Music_Combat':'combat','Music_System':'system','Music_Loading':'system'}.get(row['bank'],'unclassified')
   row['dependencies']=[]
   for w in row['wem_ids']:
    candidates=[base/'wem'/f'{w}.wem',base.parent/f'{w}.media.wem',base.parent/'Media'/f'{w}.wem']
    f=next((c for c in candidates if c.exists()),None)
    row['dependencies'].append({'wem_id':w,'path':str(f) if f else None,'sha256':sha(f) if f else None})
   rows.append(row)
 dump(Path('data/inventory.json'),{'schema_version':1,'generated_at':datetime.datetime.now(datetime.timezone.utc).isoformat(),'sources':{k:str(v) for k,v in SOURCES.items()},'counts':dict(collections.Counter(r['status'] for r in rows)),'entries':rows})
 print(collections.Counter(r['status'] for r in rows));print(collections.Counter(r.get('bank') for r in rows)); print('missing dependencies',sum(d['path'] is None for r in rows for d in r.get('dependencies',[])))
 return rows
if __name__=='__main__':scan()
