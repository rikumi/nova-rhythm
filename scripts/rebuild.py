REFS = REPOSITORY/'references'
CATEGORIES = {'Music_Outfit': 'outfit', 'Music_AVG': 'story',
              'Music_Combat': 'combat', 'Music_System': 'system', 'Music_Loading': 'system'}
SOURCE_DIRS = {'install': 'xtlr_Data/StreamingAssets/InstallResource/txtp',
               'version': 'Persistent_Store/SoundBanks/txtp'}
FILE_LINE = re.compile(r'^(\s*)(.*?\.(?:wem|bnk))(?=\s|$)(.*)$')


def read(path, default=None):
    return json.loads(path.read_text(encoding='utf-8-sig')) if path.exists() else default


def write(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix+'.tmp')
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2)+'\n', encoding='utf8')
    temp.replace(path)


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def local_names(game, work):
    names = {int(r['id']): r['objectName'] for r in read(REFS/'analysis/wwise_objects.json', [])}
    names.update({int(r['id']): r['name'] for r in read(REFS/'analysis/wwise_hash_names.json', [])})
    candidates = [game/'Persistent_Store/AssetBundles/audio.unity3d',
                  game/'xtlr_Data/StreamingAssets/InstallResource/audio.unity3d']
    bundle = next((p for p in candidates if p.is_file()), None)
    if bundle:
        source_hash = digest(bundle)
        cache = read(work/'wwise_names.json', {})
        if cache.get('source_sha256') != source_hash:
            import UnityPy
            objects = {}
            for obj in UnityPy.load(str(bundle)).objects:
                if obj.type.name == 'MonoBehaviour':
                    try:
                        data = obj.read_typetree()
                        if 'objectName' in data and 'id' in data:
                            objects[str(data['id'])] = data['objectName']
                    except ValueError:
                        continue
            cache = {'source_sha256': source_hash, 'names': objects}
            write(work/'wwise_names.json', cache)
        names.update({int(k): v for k, v in cache['names'].items()})
    return names


def states(filename, names):
    return [{'group_id': int(g), 'value_id': int(v), 'group': names.get(int(g), g),
             'value': names.get(int(v), v)} for g, v in re.findall(r'\((\d+)=(\d+)\)', filename)]


def portable_recipe(text, parent, game):
    """Keep TXTP directives; relocate audio inputs and reject paths outside game."""
    lines, dependencies = [], []
    for line in text.split('# AUTOGENERATED')[0].splitlines():
        if not line.strip() or line.lstrip().startswith('#'):
            continue
        line = line.split('##')[0].rstrip()
        match = FILE_LINE.match(line)
        if match:
            name = match[2].replace('{{GAME}}', game.as_posix())
            source = (parent/name).resolve()
            if not source.exists() and source.suffix.lower() == '.bnk':
                candidate = source.parent.parent/source.name
                if candidate.exists():
                    source = candidate
            if not source.is_relative_to(game):
                raise ValueError(f'TXTP input outside game: {source}')
            dependencies.append(source)
            line = match[1]+'{{GAME}}/'+source.relative_to(game).as_posix()+match[3]
        lines.append(line)
    if not dependencies:
        raise ValueError('No supported WEM/BNK inputs in TXTP')
    return '\n'.join(lines)+'\n', list(dict.fromkeys(dependencies))


def scan(game, names):
    known = read(REFS/'routes.json')['entries']
    by_name = {(r['source'], r['filename']): r for r in known if r['source'] in SOURCE_DIRS and not r.get('parent_id')}
    rows, errors, seen = [], [], set()
    for origin, directory in SOURCE_DIRS.items():
        for path in sorted((game/directory).glob('*.txtp')):
            bank = re.search(r'Music_[A-Za-z]+', path.name)
            if not bank:  # UI sound recipes are handled by the research scripts.
                continue
            prior = by_name.get((origin, path.name))
            row = {'id': prior.get('id', origin+'-'+hashlib.sha256(path.name.encode()).hexdigest()[:12]) if prior else origin+'-'+hashlib.sha256(path.name.encode()).hexdigest()[:12],
                   'source': origin, 'filename': path.name, 'source_sha256': digest(path),
                   'bank': bank[0], 'category': CATEGORIES.get(bank[0], 'unclassified'),
                   'gamesyncs': states(path.name, names), 'status': 'inventoried',
                   'snapshot_recipe_unchanged': bool(prior and digest(path) == prior.get('sha256'))}
            seen.add(row['id'])
            if 'transition' in path.name.lower() or any(str(g['value']).lower() == 'transition' for g in row['gamesyncs']):
                row['status'] = 'excluded_transition'
            else:
                try:
                    row['recipe'], _ = portable_recipe(path.read_text(encoding='utf-8-sig'), path.parent, game)
                except Exception as exc:
                    row.update(status='failed', error=str(exc)); errors.append(row)
            rows.append(row)
    # Missing original routes remain available as explicit frozen recipes. Updated
    # local recipes win; stale supplemental routes are reported if inputs disappeared.
    for prior in known:
        if not prior.get('recipe_file') or prior['id'] in seen:
            continue
        if prior.get('parent_id'):
            continue  # Expand original recipes below instead of frozen branches.
        row = {k: prior[k] for k in ['id', 'source', 'filename', 'bank', 'category', 'gamesyncs']}
        row['gamesyncs'] = states(row['filename'], names)
        try:
            file = REFS/prior['recipe_file']
            if digest(file) != prior['recipe_sha256']:
                raise ValueError(f'Reference TXTP checksum mismatch: {file}')
            row['recipe'], _ = portable_recipe(file.read_text(encoding='utf8'), game, game)
            row['status'] = 'excluded_transition' if any(str(g['value']).lower() == 'transition' for g in row['gamesyncs']) else 'inventoried'
        except Exception as exc:
            row.update(status='failed', error=str(exc)); errors.append(row)
        rows.append(row)
    variants = []
    for row in rows:
        matches = list(re.finditer(r'-R(\d+)>(?:\d+|-)', row.get('recipe', '')))
        if not matches or row['status'] != 'inventoried':
            continue
        count = 1
        for match in matches:
            count *= int(match[1])
        if count > 512:
            errors.append({'id': row['id'], 'error': f'{count} random branches; requires manual selection'})
            continue
        # vgmstream's >- means "play all", not a random runtime choice. Preserve
        # that deterministic arrangement as well as explicit selectable branches.
        row['expanded_random_branches'] = count
        for choices in itertools.product(*(range(1, int(m[1])+1) for m in matches)):
            variant = copy.deepcopy(row); iterator = iter(choices)
            variant.update(id=row['id']+'-r'+''.join(map(str, choices)), parent_id=row['id'],
                           random_choices=list(choices), status='inventoried')
            variant['recipe'] = re.sub(r'-R(\d+)>(?:\d+|-)', lambda m: f'-R{m[1]}>{next(iterator)}', row['recipe'])
            variants.append(variant)
    return rows+variants, errors


def command(args, timeout=240):
    result = subprocess.run([str(x) for x in args], capture_output=True, timeout=timeout)
    if result.returncode:
        raise RuntimeError(result.stderr.decode('utf8', errors='replace')[-2000:] or result.stdout.decode('utf8', errors='replace')[-2000:])
    return result.stdout.decode('utf8', errors='replace')


def render(row, game, work, cli, ffmpeg, cache, input_hashes, tool_signature):
    try:
        recipe, deps = portable_recipe(row['recipe'], game, game)
        fingerprints = [[p.relative_to(game).as_posix(), input_hashes[p]] for p in deps]
        key = hashlib.sha256(json.dumps([recipe, fingerprints, tool_signature], sort_keys=True).encode()).hexdigest()
        prior = cache.get(key)
        flac = work/f'lossless/{key}.flac'
        if prior and flac.exists() and digest(flac) == prior.get('flac_sha256'):
            return row | prior | {'render_key': key, 'cache_hit': True}
        temp = work/'render'; temp.mkdir(parents=True, exist_ok=True)
        txtp, wav = temp/f'{key}.txtp', temp/f'{key}.wav'
        txtp.write_text(recipe.replace('{{GAME}}', game.as_posix()), encoding='utf8')
        metadata = json.loads(command([cli, '-I', '-m', txtp]))
        command([cli, '-i', '-o', wav, txtp])
        flac.parent.mkdir(parents=True, exist_ok=True)
        command([ffmpeg, '-v', 'error', '-y', '-i', wav, '-c:a', 'flac', '-compression_level', '8', flac])
        pcm = command([ffmpeg, '-v', 'error', '-i', flac, '-f', 'hash', '-hash', 'sha256', '-']).strip().split('=')[-1]
        wav.unlink(missing_ok=True)
        audio = {'sample_rate': metadata['sampleRate'], 'channels': metadata['channels'],
                 'number_of_samples': metadata['numberOfSamples'],
                 'duration_seconds': metadata['numberOfSamples']/metadata['sampleRate'],
                 'loop': metadata.get('loopingInfo')}
        return row | {'status': 'exported', 'render_key': key, 'pcm_sha256': pcm,
                      'flac_sha256': digest(flac), 'audio': audio, 'cache_hit': False}
    except Exception as exc:
        return row | {'status': 'failed', 'error': str(exc)}


def build_manifests(results, annotations, raw_names):
    baseline_outfits = read(REPOSITORY/'public/data/outfits.json')['items']
    technical_library = read(REPOSITORY/'public/data/library.json')
    mapping = read(REPOSITORY/'public/data/story-melodies.json')
    baseline_library = apply_mapping(mapping, technical_library) if mapping else technical_library
    removed_ids = {t['id'] for t in technical_library['tracks']} - {t['id'] for t in baseline_library['tracks']}
    known = {t['id']: t for t in baseline_library['tracks']}
    groups = {g['id']: copy.deepcopy(g) | {'track_ids': [], 'outfit_references': []} for g in baseline_library['groups']}
    outfits = {o['code']: copy.deepcopy(o) | {'music': []} for o in baseline_outfits}
    music_locations = {}
    music_order = {}
    for outfit in baseline_outfits:
        for index, music in enumerate(outfit['music']):
            music_locations.setdefault(music['id'], []).append((outfit['code'], music))
            music_order[outfit['code'], music['id']] = index
    by_pcm = {}
    for row in results:
        if row.get('status') == 'exported':
            by_pcm.setdefault(row['pcm_sha256'], []).append(row)
    tracks, pending, published = [], [], {}
    for pcm, routes in sorted(by_pcm.items()):
        identifier = 'audio-'+pcm
        if identifier in removed_ids:
            continue
        if identifier in known and known[identifier]['path'] != f'/audio/{identifier}.opus':
            continue  # Explicit replacement file in the human mapping takes precedence.
        routes.sort(key=lambda r: (r['source'] != 'version', r['source'] != 'regenerated_version', r['filename']))
        source = routes[0]
        override = annotations.get('tracks', {}).get(identifier, {})
        if override.get('exclude'):
            continue
        music = dict(source['audio'], id=identifier, path=f'/audio/{identifier}.opus')
        raw_title = source['filename'].removesuffix('.txtp')
        locations = music_locations.get(identifier, [])
        if locations:
            for code, old in locations:
                playback = music | {'title': override.get('title', raw_title if raw_names else old['title'])}
                if all(old[k] == music[k] for k in ['sample_rate', 'channels', 'number_of_samples']):
                    playback['loop'] = copy.deepcopy(old['loop'])
                outfits[code]['music'].append(playback)
            published[identifier] = source
            continue
        # Explicit Wwise outfit state is sufficient to associate new music, even
        # when no human has provided its title, story or activity yet.
        linked = []
        for route in routes:
            values = {s['group']: str(s['value']) for s in route['gamesyncs']}
            match = re.fullmatch(r'outfit_(\d+)', values.get('outfit', ''))
            if not match:
                continue
            code = match[1]
            if code not in outfits:
                outfits[code] = {'id': int(code), 'code': code, 'name': 'outfit_'+code,
                                 'storyTitle': 'outfit_'+code, 'story': '', 'literary': '', 'description': '',
                                 'characters': [], 'element': 7, 'rarity': 3, 'tags': [],
                                 'cover': f'/art/{code}/cover.webp', 'thumbnail': f'/art/{code}/thumb.webp',
                                 'fullCover': f'/art/{code}/full.webp', 'staticImage': f'/art/{code}/original.png',
                                 'card': {'mask_size': 712, 'layers': []},
                                 'activity': {'id': 0, 'name': '星塔唱片', 'date': '', 'basis': 'unannotated'}, 'music': []}
            variant = '凯旋旋律' if values.get('Disc') == 'discVictory' else '核心旋律'
            if (code, variant) not in linked:
                linked.append((code, variant))
                outfits[code]['music'].append(music | {'title': override.get('title', raw_title if raw_names else variant)})
                music_order[code, identifier] = 1 if variant == '凯旋旋律' else 0
        if linked:
            published[identifier] = source
            pending.append({'id': identifier, 'suggested_title': raw_title, 'outfit_codes': sorted({c for c, _ in linked}),
                            'route_ids': [r['id'] for r in routes], 'reason': 'new_outfit_state_or_audio'})
            continue
        if music['duration_seconds'] < 60:
            continue
        if identifier in known and not raw_names:
            track = copy.deepcopy(known[identifier]) | music
            # PCM-identical aliases may specify different loop anchors. Preserve
            # the reviewed playback choice; alternate route loops stay in catalog.
            if all(known[identifier][k] == music[k] for k in ['sample_rate', 'channels', 'number_of_samples']):
                track['loop'] = copy.deepcopy(known[identifier]['loop'])
        else:
            group_id = 'raw-'+source['bank']
            groups.setdefault(group_id, {'id': group_id, 'name': source['bank'], 'date': '', 'track_ids': [], 'outfit_references': []})
            track = music | {'title': raw_title, 'source_title': raw_title, 'group_id': group_id,
                             'uses': [], 'aliases': [r['filename'] for r in routes]}
            pending.append({'id': identifier, 'suggested_title': raw_title, 'route_ids': [r['id'] for r in routes],
                            'gamesyncs': source['gamesyncs'], 'reason': 'raw_name_fallback'})
        track['title'] = override.get('title', track['title'])
        if 'group' in override:
            group = override['group']
            groups[group['id']] = groups.get(group['id'], {}) | group
            groups[group['id']].setdefault('track_ids', [])
            groups[group['id']].setdefault('outfit_references', [])
            track['group_id'] = group['id']
        tracks.append(track); groups[track['group_id']]['track_ids'].append(identifier)
        published[identifier] = source
    if not raw_names:
        # Manually supplied assets need no game route or AI annotation. Keep them
        # in staged sites, while decoded game tracks still follow render results.
        technical_ids = {t['id'] for t in technical_library['tracks']}
        available_ids = {t['id'] for t in tracks}
        for track in baseline_library['tracks']:
            manual = track['id'] not in technical_ids or track['path'] != f'/audio/{track["id"]}.opus'
            if manual and track['id'] not in available_ids:
                tracks.append(copy.deepcopy(track))
                groups[track['group_id']]['track_ids'].append(track['id'])
    items = []
    for code, outfit in outfits.items():
        if not outfit['music']:
            continue
        allowed = {'name', 'storyTitle', 'story', 'literary', 'description', 'characters', 'element', 'rarity', 'tags', 'activity'}
        outfit.update({k: v for k, v in annotations.get('outfits', {}).get(code, {}).items() if k in allowed})
        outfit['music'].sort(key=lambda m: (music_order.get((code, m['id']), 99), m['id']))
        items.append(outfit)
    # Reuse only the verified first-release links; never infer references from PCM reuse.
    valid_outfits = {o['id'] for o in items}
    for old_group in baseline_library['groups']:
        if raw_names:
            continue
        groups[old_group['id']]['outfit_references'] = [r for r in old_group.get('outfit_references', []) if r['outfit_id'] in valid_outfits]
    for outfit in items:
        annotated_activity = annotations.get('outfits', {}).get(outfit['code'], {}).get('activity')
        if not annotated_activity or not annotated_activity.get('id') or not annotated_activity.get('date'):
            continue
        activity = outfit['activity']; group_id = 'activity-'+str(activity['id'])
        group = groups.setdefault(group_id, {'id': group_id, 'name': activity['name'], 'date': activity['date'], 'track_ids': [], 'outfit_references': []})
        if not any(r['outfit_id'] == outfit['id'] for r in group['outfit_references']):
            group['outfit_references'].append({'outfit_id': outfit['id'], 'name': outfit['name'], 'cover': outfit['thumbnail'],
                                               'content_ids': [m['id'] for m in outfit['music']], 'basis': 'explicit first-release annotation'})
    items.sort(key=lambda o: (o['activity'].get('date', ''), o['activity'].get('id', 0), int(o['code'])), reverse=True)
    selected_groups = [g for g in groups.values() if g['track_ids'] or g['outfit_references']]
    selected_groups.sort(key=lambda g: g.get('date', ''), reverse=True)
    track_order = {t['id']: index for index, t in enumerate(baseline_library['tracks'])}
    group_orders = {g['id']: {identifier: index for index, identifier in enumerate(g['track_ids'])} for g in baseline_library['groups']}
    for group in selected_groups:
        order = group_orders.get(group['id'], {})
        group['track_ids'].sort(key=lambda identifier: (order.get(identifier, len(order)), identifier))
    tracks.sort(key=lambda t: (track_order.get(t['id'], len(track_order)), t['id']))
    return {'schemaVersion': 1, 'items': items}, {'schema_version': 2, 'groups': selected_groups, 'tracks': tracks}, pending, published


def extract_new_art(outfits, game, work, output):
    """Use native prefab transforms for new discs; no guessed layer geometry."""
    from PIL import Image
    import UnityPy
    from disc_layout import layout
    errors = []
    baseline_codes = {o['code'] for o in read(REPOSITORY/'public/data/outfits.json')['items']}
    for outfit in outfits['items']:
        code = outfit['code']
        if code in baseline_codes:
            continue
        candidates = [game/f'Persistent_Store/AssetBundles/disc_{code}.unity3d',
                      game/f'xtlr_Data/StreamingAssets/InstallResource/disc_{code}.unity3d']
        bundle = next((p for p in candidates if p.exists()), None)
        try:
            if not bundle:
                raise FileNotFoundError(f'disc_{code}.unity3d')
            textures = {}
            for obj in UnityPy.load(str(bundle)).objects:
                if obj.type.name == 'Texture2D':
                    data = obj.read()
                    if re.match(r'^'+re.escape(code)+r'[_\d]', data.m_Name):
                        textures[data.m_Name] = data.image
            cover = textures.get(code+'_B') or textures.get(code+'_b')
            if cover is None:
                raise ValueError('No static disc cover texture found')
            folder = output/f'art/{code}'; folder.mkdir(parents=True, exist_ok=True)
            cover.save(folder/'original.png')
            cover.save(folder/'full.webp', 'WEBP', quality=93, method=5)
            for name, size in [('cover', 1400), ('thumb', 280)]:
                image = cover.copy(); image.thumbnail((size, size), Image.Resampling.LANCZOS)
                image.save(folder/f'{name}.webp', 'WEBP', quality=90, method=5)
            art = {'source_bundle': str(bundle), 'images': [{'name': name} for name in textures]}
            outfit['card'] = layout({'code': code, 'artwork': art})
            for layer in outfit['card']['layers']:
                textures[layer['name']].save(folder/(layer['name']+'.webp'), 'WEBP', quality=90, method=5)
            write(work/f'art/{code}.json', {'bundle': bundle.relative_to(game).as_posix(),
                                          'source_sha256': digest(bundle), 'card': outfit['card']})
        except Exception as exc:
            errors.append({'outfit_code': code, 'error': str(exc)})
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game-dir', default=os.environ.get('NOVA_GAME_DIR'), required=not os.environ.get('NOVA_GAME_DIR'))
    parser.add_argument('--work-dir', type=Path, default=REPOSITORY/'.build/import')
    parser.add_argument('--output', type=Path, default=REPOSITORY/'.build/site/public')
    parser.add_argument('--vgmstream', type=Path, default=Path(os.environ.get('VGMSTREAM_CLI', REPOSITORY/'tools/vgmstream/vgmstream-cli.exe')))
    parser.add_argument('--ffmpeg', type=Path)
    parser.add_argument('--annotations', type=Path, default=REFS/'annotations.json')
    parser.add_argument('--scan-only', action='store_true')
    parser.add_argument('--selected-only', action='store_true', help='Decode one available route per selected identity, plus new or changed routes.')
    parser.add_argument('--raw-names', action='store_true', help='Ignore existing translated audio labels and activity groups.')
    parser.add_argument('--route', action='append', help='Restrict to explicit route IDs (repeatable; diagnostic partial build).')
    parser.add_argument('--jobs', type=int, default=4)
    args = parser.parse_args()
    game = Path(args.game_dir).resolve()
    if not game.is_dir():
        parser.error(f'Game directory does not exist: {game}')
    work, output = protect_output(args.work_dir, game), protect_output(args.output, game)
    # Never silently replace the checked-in site or any ancestor of it.
    source_public = REPOSITORY/'public'
    for path in [work, output]:
        if path == REPOSITORY or path in REPOSITORY.parents or path == source_public or path in source_public.parents or source_public in path.parents:
            parser.error('Use a separate staging output, e.g. .build/site/public; source public/ is protected.')
    if work == output or work in output.parents or output in work.parents:
        parser.error('Work directory and output directory must be disjoint.')
    names = local_names(game, work)
    rows, errors = scan(game, names)
    for row in rows:
        if row['status'] != 'inventoried':
            continue
        _, dependencies = portable_recipe(row['recipe'], game, game)
        missing = [p.relative_to(game).as_posix() for p in dependencies if not p.is_file()]
        if missing:
            row.update(status='failed', error='Missing game inputs: '+', '.join(missing))
            errors.append({'id': row['id'], 'error': row['error']})
    write(work/'inventory.json', {'entries': rows, 'errors': errors})
    counts = {status: sum(r['status'] == status for r in rows) for status in sorted({r['status'] for r in rows})}
    print('Inventory:', counts, flush=True)
    if args.scan_only:
        print(f'Read-only scan complete: {work}/inventory.json'); return 1 if errors else 0
    if args.jobs < 1:
        parser.error('--jobs must be positive')
    if not args.vgmstream.is_file():
        parser.error('vgmstream-cli not found; pass --vgmstream or set VGMSTREAM_CLI. See docs/rebuilding.md.')
    import imageio_ffmpeg
    ffmpeg = args.ffmpeg or Path(imageio_ffmpeg.get_ffmpeg_exe())
    cli = args.vgmstream.resolve()
    eligible = [r for r in rows if r['status'] == 'inventoried']
    if args.selected_only:
        selection = read(REFS/'selection.json')['contents']
        available = {r['id'] for r in eligible}
        chosen = {next((route for route in content['route_ids'] if route in available), '') for content in selection if content['selected']}
        old_ids = {r['id'] for r in read(REFS/'routes.json')['entries'] if r.get('id')}
        eligible = [r for r in eligible if r['id'] in chosen or r['id'] not in old_ids or r.get('snapshot_recipe_unchanged') is False]
    if args.route:
        eligible = [r for r in eligible if r['id'] in args.route]
        if {r['id'] for r in eligible} != set(args.route):
            parser.error('Requested route is missing, excluded or nondeterministic; inspect inventory.json.')
    if not eligible:
        parser.error('No eligible music recipes found.')
    input_hashes = {}
    # Hash source bytes, not mtimes, so changed WEMs invalidate incremental cache.
    ready = []
    for row in eligible:
        try:
            _, deps = portable_recipe(row['recipe'], game, game)
            for dep in deps:
                if dep not in input_hashes:
                    input_hashes[dep] = digest(dep)
            ready.append(row)
        except Exception as exc:
            errors.append({'id': row['id'], 'error': str(exc)})
    signature = [digest(cli), command([ffmpeg, '-version']).splitlines()[0], 'pcm-ignore-loop-flac8-opus160k-v1']
    cache = read(work/'cache.json', {})
    # Coalesce byte-identical recipes before starting concurrent writers.
    unique, aliases = {}, {}
    for row in ready:
        key = row['recipe']
        aliases.setdefault(key, []).append(row)
        unique.setdefault(key, row)
    results = []
    print(f'Decoding {len(unique)} recipes ({len(ready)} routes)', flush=True)
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        futures = {pool.submit(render, r, game, work, cli, ffmpeg, cache, input_hashes, signature): key for key, r in unique.items()}
        for future in as_completed(futures):
            result = future.result()
            for row in aliases[futures[future]]:
                results.append(row | {k: v for k, v in result.items() if k not in row or k == 'status'})
            if result['status'] == 'exported':
                cache[result['render_key']] = {k: result[k] for k in ['status', 'render_key', 'pcm_sha256', 'flac_sha256', 'audio']}
                write(work/'cache.json', cache)
            else:
                errors.append({'id': result['id'], 'error': result['error']})
            if len(results) % 25 == 0 or result['status'] != 'exported':
                print(f'{len(results)}/{len(ready)}', result['status'], flush=True)
    write(work/'catalog.json', {'schema_version': 1, 'tracks': results})
    outfits, library, pending, published = build_manifests(results, read(args.annotations, {}), args.raw_names)
    # Only static website inputs go to output. Research data stays in work/.
    for source in sorted(source_public.rglob('*')):
        if source.is_file() and source.relative_to(source_public).parts[0] not in ['audio', 'data']:
            target = output/source.relative_to(source_public); target.parent.mkdir(parents=True, exist_ok=True)
            if not target.exists() or digest(target) != digest(source):
                shutil.copy2(source, target)
    for encoded_count, (identifier, row) in enumerate(published.items(), 1):
        target = output/f'audio/{identifier}.opus'; target.parent.mkdir(parents=True, exist_ok=True)
        opus_key = hashlib.sha256(json.dumps([row['render_key'], signature]).encode()).hexdigest()
        sidecar = work/f'encoded/{identifier}.json'
        old = read(sidecar, {})
        if not (target.exists() and old.get('key') == opus_key and digest(target) == old.get('sha256')):
            temp = target.with_suffix('.tmp.opus')
            command([ffmpeg, '-v', 'error', '-y', '-i', work/f'lossless/{row["render_key"]}.flac',
                     '-vn', '-map_metadata', '-1', '-c:a', 'libopus', '-b:a', '160k', '-vbr', 'on',
                     '-compression_level', '10', '-frame_duration', '20', '-ar', '48000', '-threads', '1', temp])
            temp.replace(target)
            write(sidecar, {'key': opus_key, 'sha256': digest(target)})
        if encoded_count % 25 == 0:
            print(f'Encoded or verified {encoded_count}/{len(published)} audio files', flush=True)
    errors.extend(extract_new_art(outfits, game, work, output))
    for track in library['tracks']:
        if track['id'] in published or track['path'].startswith('https://'):
            continue
        source = (source_public/track['path'].lstrip('/')).resolve()
        if not source.is_relative_to(source_public.resolve()) or not source.is_file():
            errors.append({'id': track['id'], 'error': 'Missing manually mapped audio: '+track['path']})
            continue
        target = output/track['path'].lstrip('/'); target.parent.mkdir(parents=True, exist_ok=True)
        if not target.exists() or digest(target) != digest(source):
            shutil.copy2(source, target)
    # Remove obsolete generated audio only, never recursively remove an output tree.
    audio_dir = output/'audio'
    if audio_dir.is_dir():
        needed_paths = {t['path'] for t in library['tracks']}
        for file in audio_dir.glob('audio-*.opus'):
            if file.stem not in published and '/audio/'+file.name not in needed_paths:
                file.unlink()
    write(output/'data/outfits.json', outfits)
    write(output/'data/library.json', library)
    write(output/'data/story-melodies.json', to_mapping(library, read(source_public/'data/story-melodies.json')))
    write(work/'pending_annotations.json', pending)
    write(work/'report.json', {'routes': len(rows), 'rendered_routes': len(results), 'cache_hits': sum(r.get('cache_hit', False) for r in results),
                             'published_audio': len(published), 'pending_annotations': len(pending), 'errors': errors})
    print(f'Exported {len(published)} unique audio files; {len(pending)} pending labels; {len(errors)} errors.', flush=True)
    print(f'Staged public directory: {output}')
    return 1 if errors else 0


