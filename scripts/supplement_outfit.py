import json,re,hashlib
from pathlib import Path
from pipeline_paths import ROOT as root
rows=json.loads((root/'data/inventory.json').read_text(encoding='utf8'))['entries']
def route(row):return row.get('bank'),tuple(sorted((g['group_id'],g['value_id']) for g in row.get('gamesyncs',[])))
known={route(r) for r in rows};out=[]
files=list((root/'data/generated/version').glob('*.txtp'))+list((root/'data/generated/version_all').glob('*.txtp'))
for p in sorted(files,key=lambda p:('{d}' in p.name,p.name)):
 if 'transition' in p.name:continue
 gs=[{'group_id':int(a),'value_id':int(b)} for a,b in re.findall(r'\((\d+)=(\d+)\)',p.name)]
 if not gs:continue
 bank=re.search(r'Music_[A-Za-z]+',p.name)[0]
 text=p.read_text(encoding='utf8');row={'id':'supplemental-'+hashlib.sha256(p.name.encode()).hexdigest()[:12],'status':'inventoried','source':'regenerated_version','path':str(p),'filename':p.name,'sha256':hashlib.sha256(text.encode()).hexdigest(),'bank':bank,'category':{'Music_Outfit':'outfit','Music_AVG':'story','Music_Combat':'combat','Music_System':'system'}[bank],'gamesyncs':gs,'recipe':text.split('# AUTOGENERATED')[0].strip(),'wem_ids':sorted(set(re.findall(r'(\d+)\.wem',text))),'event_ids':re.findall(r'CAkEvent\[\d+\]\s+(\d+)',text),'duration_ms':[float(x) for x in re.findall(r'fDuration: ([\d.]+)',text)],'random':'{r}' in p.name,'provenance':'Missing state route reconstructed from current version BNK using wwiser -gd in project directory'}
 if route(row) in known:continue
 known.add(route(row));out.append(row)
(root/'data/supplemental_inventory.json').write_text(json.dumps(out,ensure_ascii=False,indent=2),encoding='utf8');print('supplemental routes',len(out))
